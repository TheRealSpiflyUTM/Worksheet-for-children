CREATE TABLE mini_game_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    worksheet_result_id BIGINT NOT NULL,
    worksheet_item_id BIGINT NOT NULL,
    score INT NOT NULL,
    max_score INT NOT NULL,
    time_seconds INT NOT NULL,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,

    CONSTRAINT fk_mini_game_result_worksheet_result
        FOREIGN KEY (worksheet_result_id) REFERENCES worksheet_result(id) ON DELETE CASCADE,

    CONSTRAINT fk_mini_game_result_worksheet_item
        FOREIGN KEY (worksheet_item_id) REFERENCES worksheet_item(id),

    CONSTRAINT uq_mini_game_result_item
        UNIQUE (worksheet_result_id, worksheet_item_id)
);