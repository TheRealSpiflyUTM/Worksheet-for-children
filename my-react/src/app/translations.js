export const ro = Object.fromEntries(
  entries.split("\n").map((line) => line.split("|")),
);
export function initialLanguage(
  storage = globalThis.localStorage,
  browser = globalThis.navigator?.language,
) {
  try {
    const saved = storage?.getItem("worksheet-language");
    if (saved === "en" || saved === "ro") return saved;
  } catch {
    /* Storage may be disabled. */
  }
  return browser?.toLowerCase().startsWith("ro") ? "ro" : "en";
}
export function translate(language, text) {
  return language === "ro" ? ro[text] || text : text;
}
